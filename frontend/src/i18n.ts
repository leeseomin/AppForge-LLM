const messages: Record<Locale, Record<TranslationKey, string>> = { ko, en };

export function normalizeLocale(value: unknown): Locale {
  return value === 'en' ? 'en' : DEFAULT_LOCALE;
}

export function translate(locale: Locale, key: TranslationKey, params: TranslationParams = {}): string {
  const template = messages[locale][key] ?? messages[DEFAULT_LOCALE][key] ?? key;
  return template.replace(/\{\{(\w+)\}\}/g, (match, name: string) => {
    const value = params[name];
    return value === undefined ? match : String(value);
  });
}

function readInitialLocale(): Locale {
  if (typeof window === 'undefined') return DEFAULT_LOCALE;
  try {
    return normalizeLocale(window.localStorage.getItem(LOCALE_STORAGE_KEY));
  } catch {
    return DEFAULT_LOCALE;
  }
}

const localeState = ref<Locale>(readInitialLocale());

function syncDocumentLanguage(locale: Locale) {
  if (typeof document !== 'undefined') {
    document.documentElement.lang = locale;
  }
}

syncDocumentLanguage(localeState.value);

export function setLocale(locale: Locale) {
  localeState.value = normalizeLocale(locale);
  syncDocumentLanguage(localeState.value);
  if (typeof window !== 'undefined') {
    try {
      window.localStorage.setItem(LOCALE_STORAGE_KEY, localeState.value);
    } catch {
      // Language selection still works for the current session when storage is unavailable.
    }
  }
}

export function useI18n() {
  return {
    locale: readonly(localeState),
    setLocale,
    t: (key: TranslationKey, params?: TranslationParams) => translate(localeState.value, key, params),
  };
}

export function translateCurrent(key: TranslationKey, params?: TranslationParams): string {
  return translate(localeState.value, key, params);
}
